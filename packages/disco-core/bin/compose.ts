#!/usr/bin/env tsx
/**
 * disco compose — the deterministic baseline.
 *
 * Builds a complete, valid spec from the recommender alone, with no model in
 * the loop. Two reasons it exists:
 *
 *   1. It is the fallback. If the agent is unavailable or its spec fails the
 *      gate twice, you still get a correct dashboard.
 *   2. It is the floor the agent has to beat. The composer skill starts from
 *      this and edits it, rather than inventing a spec from nothing — which is
 *      where models produce plausible bindings to fields that do not exist.
 *
 *   npm run compose -- <slug> ["the question this should answer"]
 */
import { recommend, chooseMode, type Candidate } from "../src/recommend";
import { validate, formatIssues } from "../src/validate";
import type { DashboardSpec } from "../src/spec";
import type { DatasetProfile } from "../src/types";
import { buildBaseTables } from "../src/profile";
import { die, exists, read, readJson, writeJson } from "./shared";

const [slug, intentArg] = process.argv.slice(2);
if (!slug) die("usage: npm run compose -- <slug> [\"question\"]");

const profilePath = `outputs/${slug}/profile.json`;
if (!exists(profilePath)) die(`no profile at "${profilePath}". Run: npm run profile -- <input> --slug ${slug}`);

const profile = readJson<DatasetProfile>(profilePath);
const table = profile.tables[0];
const intent = intentArg ?? `Overview of ${table.rowCount} records from ${profile.source}`;

const candidates = recommend(table);

/**
 * Pick a coherent set rather than the top N by score: four headline tiles, the
 * trend, two breakdowns, one distribution, and the detail table. A dashboard is
 * a composition, and eight of the highest-scoring blocks would be eight KPIs.
 */
function selectLayout(all: Candidate[]): Candidate[] {
  const take = (kind: string, n: number) => all.filter((c) => c.block.kind === kind).slice(0, n);
  return [
    ...take("kpi", 4),
    ...take("timeseries", 1),
    ...take("pie", 1),
    ...take("bar", 2),
    ...take("histogram", 1),
    ...take("scatter", 1),
    ...take("table", 1),
  ];
}

const chosen = selectLayout(candidates);
if (chosen.length === 0) die("the recommender produced no viable blocks for this data.");

// Deduplicate derivations: several blocks legitimately share a frame.
const derivations = [...new Map(chosen.flatMap((c) => c.derivations).map((d) => [d.id, d])).values()];

const spec: DashboardSpec = {
  $schema: "disco/v1",
  id: slug.replace(/[^a-z0-9_]/g, "_"),
  title: intentArg ?? `${table.id === "raw" ? "Overview" : table.id}`,
  subtitle: `${table.rowCount.toLocaleString()} records · ${table.fields.length} fields`,
  intent,
  dataset: { source: profile.source, mode: chooseMode(table.rowCount), rowCount: table.rowCount },
  controls: [],
  derivations,
  blocks: chosen.map((c) => c.block),
  notes: [
    ...profile.warnings,
    "Generated by the rules-based composer. Every figure is computed by the derivation engine, not by a model.",
  ],
};

/* Validate against the real rows before writing — the same gate the agent faces. */
const doc = JSON.parse(read(profile.source));
const base = buildBaseTables(doc, profile);

const result = validate(spec, base, profile);
process.stdout.write(`${formatIssues(result.issues)}\n\n`);

if (!result.ok) {
  die("the baseline composer produced an invalid spec — this is a bug in recommend.ts, not in your data.");
}

const out = `outputs/${slug}/spec.json`;
writeJson(out, spec);
process.stdout.write(`WROTE ${out}  (${spec.blocks.length} blocks, ${spec.derivations.length} derivations)\n\nNext: npm run materialize -- ${slug}\n\n`);
