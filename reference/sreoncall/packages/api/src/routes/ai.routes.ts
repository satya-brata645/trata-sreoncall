// ─── POST /api/v1/ai/triage/incident/:id ─────────────────────────────────────

router.post('/triage/incident/:id', rbac('incidents:read'), async (req: Request, res: Response) => {
  const id = req.params['id'] as string;
  const { doc } = await getIncidentDoc(req.tenantId, id);

  let result: string;

  if (isAIAvailable()) {
    const ctx = await buildIncidentContext(req.tenantId, id);
    const contextText = ctx ? formatContextForPrompt(ctx) : `Incident: ${doc.title}\nStatus: ${doc.status}`;
    await checkAiBudget(req.tenantId, estimateTokens(contextText));
    const completion = await generateCompletion({
      system: TRIAGE_SYSTEM_PROMPT,
      userMessage: `Analyze and triage this incident:\n\n${contextText}`,
    });
    if (completion.model !== 'fallback') {
      await consumeAiTokens(req.tenantId, completion.input_tokens, completion.output_tokens);
    }
    result = completion.model === 'fallback' ? fallbackTriage(doc) : completion.text;
  } else {
    result = fallbackTriage(doc);
  }

  res.json({ result, incident_id: id, generated_at: new Date().toISOString() });
});

