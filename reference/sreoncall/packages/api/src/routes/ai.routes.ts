// ─── Helpers ─────────────────────────────────────────────────────────────────

function priorityLabel(p: number | string): string {
  if (typeof p === 'string') return p;
  const map: Record<number, string> = { 1: 'high', 2: 'high', 3: 'medium', 4: 'low', 5: 'low' };
  return map[p] || 'medium';
}

function severityLabel(p: number): string {
  const map: Record<number, string> = { 1: 'CRITICAL', 2: 'HIGH', 3: 'MEDIUM', 4: 'LOW', 5: 'INFO' };
  return map[p] || 'MEDIUM';
}

/** Look up incident from new Incident model, falling back to legacy Ticket model. */
async function getIncidentDoc(tenantId: Types.ObjectId, id: string) {
  // Try new Incident model first
  const incident = await Incident.findOne({ _id: id, tenant_id: tenantId });
  if (incident) return { source: 'incident' as const, doc: incident };

  // Fall back to legacy Ticket model
  const ticket = await Ticket.findOne({ _id: id, tenant_id: tenantId, type: 'incident' })
    .populate('reporter_id', 'name email')
    .populate('assignee_id', 'name email');
  if (ticket) return { source: 'ticket' as const, doc: ticket };

  throw AppError.notFound('Incident');
}

// ─── Fallback generators (used when OPENAI_API_KEY is not set) ────────────

function fallbackTriage(incident: any): string {
  const priority = (incident.priority || incident.severity || 3) as number;
  const pLabel = priorityLabel(priority);
  const severity = severityLabel(priority);
  const title = incident.title || 'Unknown incident';
  return [
    `## Auto-Triage Analysis`,
    ``,
    `**Incident:** ${title}`,
    `**Severity:** ${severity} (${pLabel})`,
    `**Status:** ${incident.status}`,
    ``,
    `### Recommended Actions`,
    `1. Verify the scope and impact of the incident`,
    `2. Check related services and dependencies for cascading failures`,
    `3. Engage the on-call engineer for ${priority <= 2 ? 'immediate' : 'standard'} response`,
    `4. Open a war room channel if not already done`,
    ``,
    `### Initial Assessment`,
    `Based on the incident description, this appears to be a ${severity.toLowerCase()} severity issue. ` +
    `Priority escalation to ${priority === 1 ? 'all stakeholders' : priority === 2 ? 'team leads' : 'on-call team'} is recommended.`,
    ``,
    `*Generated by SREonCall AI Copilot (template mode — configure OPENAI_API_KEY for AI-powered analysis)*`,
  ].join('\n');
}

function fallbackRCA(incident: any): string {
  const title = incident.title || 'Unknown incident';
  const description = incident.description || '';
  const resolvedAt = incident.resolvedAt || incident.resolved_at;
  return [
    `## Root Cause Analysis`,
    ``,
    `**Incident:** ${title}`,
    `**Analysis Date:** ${new Date().toISOString().split('T')[0]}`,
    ``,
    `### Summary`,
    description ? `${description.slice(0, 300)}${description.length > 300 ? '...' : ''}` : 'No description provided.',
    ``,
    `### Probable Root Causes`,
    `1. **Primary cause**: Investigate recent deployments, configuration changes, or infrastructure events in the 24h window preceding the incident`,
    `2. **Contributing factors**: Load spike, dependency failures, or resource exhaustion`,
    `3. **Detection gap**: Alert thresholds may need tuning for earlier detection`,
    ``,
    `### Timeline Reconstruction`,
    `- T+0: Incident declared`,
    `- T+?: Alert fired (check monitoring)`,
    `- T+?: On-call notified`,
    `- T+?: Incident resolved (${resolvedAt ? new Date(resolvedAt).toISOString() : 'pending'})`,
    ``,
    `### Next Steps`,
    `1. Review deployment logs and change records from the incident window`,
    `2. Collect metrics from Prometheus/Grafana for the affected period`,
    `3. Document findings in a post-mortem`,
    ``,
    `*Generated by SREonCall AI Copilot (template mode — configure OPENAI_API_KEY for AI-powered analysis)*`,
  ].join('\n');
}

