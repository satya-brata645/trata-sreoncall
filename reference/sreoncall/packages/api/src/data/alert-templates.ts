  condition: {
    metric: string;
    operator: 'gt' | 'lt' | 'gte' | 'lte' | 'eq';
    threshold: number;
    window_minutes: number;
  };
  for_duration_seconds: number;
  /** Only show this template when the tenant has a connection matching this vendor (null = always show) */
  requires_vendor: string | null;
